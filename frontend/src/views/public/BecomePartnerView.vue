<script setup lang="ts">
import { ref } from 'vue'
import axios from 'axios'

const form = ref({
    full_name: '',
    email: '',
    phone: '',
    legal_status: '',
    company_size: '',
    country: '',
    subject: '',
    description: ''
})

const isSubmitting = ref(false)
const successMsg = ref('')
const errorMsg = ref('')

const handleSubmit = async () => {
    isSubmitting.value = true
    successMsg.value = ''
    errorMsg.value = ''
    
    // Construct B2B email message body to store inside existing ContactMessage table
    const constructedMessage = `
[DEMANDE DE PARTENARIAT B2B]
Sujet : ${form.value.subject}
Statut Juridique : ${form.value.legal_status}
Taille de l'entreprise : ${form.value.company_size}
Description :
${form.value.description}
    `.trim()

    const payload = {
        first_name: form.value.full_name,
        last_name: '(Partenaire)',
        email: form.value.email,
        phone: form.value.phone,
        country: form.value.country,
        message: constructedMessage
    }

    try {
        // Post to public contact endpoint (Double prefix compatibility)
        await axios.post('/public/contact', payload)
        successMsg.value = 'Votre demande de partenariat a été enregistrée avec succès. Notre responsable B2B vous recontactera très rapidement !'
        
        // Reset form
        form.value = {
            full_name: '',
            email: '',
            phone: '',
            legal_status: '',
            company_size: '',
            country: '',
            subject: '',
            description: ''
        }
    } catch (e: any) {
        errorMsg.value = e.response?.data?.message || "Erreur lors de l'envoi de votre demande. Veuillez réessayer."
    } finally {
        isSubmitting.value = false
    }
}
</script>

